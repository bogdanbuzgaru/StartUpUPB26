export function errorMessage(
  t: Dict,
  err: { code: ErrorCode; params?: Params } | undefined,
): string | undefined {
  if (!err) return undefined;
  const entry = t.errors[err.code];
  return typeof entry === "function" ? entry(err.params ?? {}) : entry;
}
